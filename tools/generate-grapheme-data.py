"""Generate FlowText's pinned Unicode 17 UAX #29 tables; use --download to fetch inputs."""
from pathlib import Path
import sys
import urllib.request

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / 'tools/unicode'
DATA.mkdir(parents=True, exist_ok=True)
FILES = {'GraphemeBreakProperty.txt': 'auxiliary/GraphemeBreakProperty.txt',
         'GraphemeBreakTest.txt': 'auxiliary/GraphemeBreakTest.txt',
         'emoji-data.txt': 'emoji/emoji-data.txt', 'DerivedCoreProperties.txt': 'DerivedCoreProperties.txt'}
if '--download' in sys.argv:
    for name, part in FILES.items():
        with urllib.request.urlopen('https://www.unicode.org/Public/17.0.0/ucd/' + part) as r:
            (DATA / name).write_bytes(r.read())
    with urllib.request.urlopen('https://www.unicode.org/license.txt') as r:
        (DATA / 'LICENSE.txt').write_bytes(r.read())

def parse(name, select):
    out = []
    for line in (DATA / name).read_text(encoding='utf-8').splitlines():
        fields = [p.strip() for p in line.split('#')[0].split(';')]
        if len(fields) < 2:
            continue
        value = select(fields)
        if value is None:
            continue
        span = fields[0].split('..')
        out.append((int(span[0], 16), int(span[-1], 16), value))
    return sorted(out)

names = ['Other', 'CR', 'LF', 'Control', 'Extend', 'ZWJ', 'Regional_Indicator',
         'Prepend', 'SpacingMark', 'L', 'V', 'T', 'LV', 'LVT']
gcb = parse('GraphemeBreakProperty.txt', lambda f: names.index(f[1]) if f[1] not in ['LV', 'LVT'] else None)
pict = parse('emoji-data.txt', lambda f: 1 if f[1] == 'Extended_Pictographic' else None)
incb_names = ['None', 'Consonant', 'Linker', 'Extend']
incb = parse('DerivedCoreProperties.txt', lambda f: incb_names.index(f[2]) if f[1] == 'InCB' else None)

def table(name, rows):
    return 'export const ' + name + ': number[] = [\n' + ''.join(
        f'  0x{a:X}, 0x{b:X}, {v},\n' for a, b, v in rows) + '];\n'

target = ROOT / 'entry/src/main/ets/editor/flowtext/model/UnicodeGraphemeData.ets'
target.write_text('// Generated by tools/generate-grapheme-data.py; Unicode 17.0.0.\n'
                  '// Unicode license: tools/unicode/LICENSE.txt. Do not edit by hand.\n'
                  + table('GRAPHEME_BREAK_DATA', gcb) + table('EXTENDED_PICTOGRAPHIC_DATA', pict)
                  + table('INDIC_CONJUNCT_DATA', incb), encoding='utf-8')
print(f'Generated {target.name}: {len(gcb) + len(pict) + len(incb)} ranges')
